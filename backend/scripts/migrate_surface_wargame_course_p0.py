def _snapshot(project: dict) -> Path:
    workspace = document_workspace_service._workspace_root(project)  # noqa: SLF001
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    target = workspace.parent / "_migration_snapshots" / f"{stamp}-before-course-p0"
    target.mkdir(parents=True, exist_ok=False)
    (target / "project.json").write_text(
        json.dumps(project, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    for relative in ["documents.json", "manifest.json", "working/document.md"]:
        source = workspace / relative
        if source.is_file():
            destination = target / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
    documents_root = workspace / "documents"
    if documents_root.exists():
        for source in documents_root.glob("*/source/document.md"):
            destination = target / "documents" / source.parent.parent.name / "source" / source.name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
        for source in documents_root.glob("*/working/document.md"):
            destination = target / "documents" / source.parent.parent.name / "working" / source.name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
        for source in documents_root.glob("*/source/presentation-manifest.json"):
            destination = target / "documents" / source.parent.parent.name / "source" / source.name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
    return target


