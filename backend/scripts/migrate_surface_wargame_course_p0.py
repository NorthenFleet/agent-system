def _extract_pptx_text(path: Path) -> tuple[int, str]:
    """Extract visible slide text without changing the source presentation."""
    try:
        with ZipFile(path) as archive:
            names = [
                name
                for name in archive.namelist()
                if re.fullmatch(r"ppt/slides/slide\d+\.xml", name)
            ]
            names.sort(key=lambda value: int(re.search(r"\d+", Path(value).stem).group()))
            slide_text = []
            for name in names:
                raw = archive.read(name)
                try:
                    root = ET.fromstring(raw)
                    values = [
                        element.text or ""
                        for element in root.iter()
                        if element.tag.endswith("}t") and (element.text or "").strip()
                    ]
                except ET.ParseError:
                    values = [
                        html.unescape(value.decode("utf-8", errors="replace"))
                        for value in re.findall(
                            rb"<a:t[^>]*>([\s\S]*?)</a:t>", raw
                        )
                        if value
                    ]
                slide_text.append(" ".join(values))
            return len(names), "\n".join(slide_text)
    except (BadZipFile, OSError, ValueError):
        return 0, ""


