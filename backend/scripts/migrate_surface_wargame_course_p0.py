def _retitle_lesson(markdown: str, title: str) -> str:
    markdown = re.sub(r"(?m)^title:\s*.+$", f"title: {json.dumps(title, ensure_ascii=False)}", markdown, count=1)
    markdown = re.sub(r"(?m)^# 第\d+讲[：:].*$", f"# {title}", markdown, count=1)
    markdown = re.sub(r"(\|\s*计划学时:\s*\|\s*)\d+(\s*\|)", r"\g<1>20\2", markdown)
    baseline_note = "> 课程基线：总计20学时，本讲2学时（120分钟）。"
    if baseline_note not in markdown:
        first_heading = markdown.find(f"# {title}")
        if first_heading >= 0:
            end = markdown.find("\n", first_heading)
            markdown = markdown[: end + 1] + "\n" + baseline_note + "\n" + markdown[end + 1 :]
    if "来源依据" not in markdown:
        markdown = markdown.rstrip() + "\n\n# 来源依据\n\n课程教学计划、《谋战·水面舰艇编队战术手工兵棋》规则体系及关联软件运行环境。\n"
    return markdown


