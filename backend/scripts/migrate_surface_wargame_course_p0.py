def _has_content_version(markdown: str) -> bool:
    return f'content_version: "{CONTENT_VERSION}"' in markdown


def _reassign_lessons(project: dict) -> list[dict]:
    current_profile = (project.get("document_spec") or {}).get("course_profile") or {}
    if current_profile.get("version") == "1.1":
        return []
    documents = multi_document_service.list_documents(project)["documents"]
    changes = []
    for row in documents:
        if row.get("product_type") != "lesson_plan" or len(row.get("course_unit_ids") or []) != 1:
            continue
        before = row["course_unit_ids"][0]
        after = LESSON_UNIT_REASSIGNMENTS.get(before, before)
        if before != after:
            multi_document_service.update_document(
                project,
                str(row["id"]),
                {"course_unit_ids": [after]},
            )
            changes.append({"document_id": row["id"], "from": before, "to": after})
    return changes


def migrate(project_id: str, dry_run: bool) -> dict:
    project = project_manager.get_project(project_id)
    if not project:
        raise SystemExit(f"Project not found: {project_id}")
    preview = course_production_service.apply_template(project, dry_run=True)
    if dry_run:
        current_profile = (project.get("document_spec") or {}).get("course_profile") or {}
        preview["lesson_reassignments"] = (
            [
                {"from": before, "to": after}
                for before, after in LESSON_UNIT_REASSIGNMENTS.items()
                if before != after
            ]
            if current_profile.get("version") != "1.1"
            else []
        )
        return preview
    snapshot = _snapshot(project)
    lesson_reassignments = _reassign_lessons(project)
    project = project_manager.get_project(project_id) or project
    result = course_production_service.apply_template(project, dry_run=False)
    project = project_manager.get_project(project_id) or project
    documents = multi_document_service.list_documents(project)["documents"]
    by_type = {}
